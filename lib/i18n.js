export function formatI18n(lang, key, vars = {}) {
  const dict = I18N[lang] || I18N.ja;
  let str = dict[key] ?? I18N.ja[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return str;
}
